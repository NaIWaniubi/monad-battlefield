/**
 * 用 solc-js 编译 Battlefield.sol，产出：
 *   contracts/artifacts/Battlefield.json   （abi + bytecode，给部署脚本）
 *   web/src/abi.ts                         （abi，给前端）
 *
 * 这样不需要装 Foundry —— 一条 npm 依赖解决编译。
 */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const solc = require("solc") as {
  version: () => string;
  compile: (input: string) => string;
};

const FILE = "Battlefield.sol";
const source = readFileSync("contracts/Battlefield.sol", "utf8");

const input = {
  language: "Solidity",
  sources: { [FILE]: { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input))) as any;

const errors = (out.errors ?? []).filter((e: any) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e: any) => e.formattedMessage).join("\n"));
  process.exit(1);
}

const c = out.contracts[FILE].Battlefield;
const bytecode: string = c.evm.bytecode.object;
if (!bytecode || bytecode.length === 0) {
  console.error("编译成功但 bytecode 为空，检查合约是否有 constructor 问题");
  process.exit(1);
}

mkdirSync("contracts/artifacts", { recursive: true });
writeFileSync(
  "contracts/artifacts/Battlefield.json",
  JSON.stringify({ abi: c.abi, bytecode: "0x" + bytecode }, null, 2) + "\n",
);
writeFileSync(
  "web/src/abi.ts",
  "// AUTO-GENERATED by scripts/build.ts —— 不要手改\n" +
    "export const ABI = " +
    JSON.stringify(c.abi, null, 2) +
    " as const;\n",
);

const size = bytecode.length / 2;
console.log(`solc ${solc.version()}`);
console.log(`✔ Battlefield 编译完成  bytecode=${size} bytes`);
console.log(`✔ contracts/artifacts/Battlefield.json`);
console.log(`✔ web/src/abi.ts`);
